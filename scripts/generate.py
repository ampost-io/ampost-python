#!/usr/bin/env python3
"""Generates the SDK's typed layer from the Ampost OpenAPI document. Standard library only.

    python scripts/generate.py                                    # from the committed openapi.json
    python scripts/generate.py --spec https://api.ampost.io/openapi.json
    python scripts/generate.py --spec ../path/to/openapi.json

With --spec, the document is first saved as openapi.json, so the snapshot and the code always match.
Output (never edit by hand):
    src/ampost/_generated/models.py     a TypedDict or Literal alias per schema
    src/ampost/_generated/resources.py  sync and async classes per tag, one method per operation
"""

from __future__ import annotations

import argparse
import json
import keyword
import re
import urllib.request
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "openapi.json"
OUT = ROOT / "src" / "ampost" / "_generated"
HEADER = "# Generated by scripts/generate.py from openapi.json. Do not edit by hand: run `python scripts/generate.py`.\n"
HTTP_METHODS = ("get", "post", "put", "patch", "delete")
REF_PREFIX = "#/components/schemas/"

# Method names that read better than the ones derived from the operationId (tag prefix stripped).
# A new operation needs no entry: it gets the derived name. Keep in step with ampost-node.
METHOD_NAMES = {
    "media_upload_create": "create_upload",
    "media_upload_status": "get_upload",
    "accounts_connect_status": "get_connect_request",
    "queue_get": "get_queue",
    "queue_update": "update_queue",
    "queue_slots": "get_queue_slots",
    "analytics_posts": "list_posts",
    "analytics_overview": "get_overview",
    "analytics_followers": "list_followers",
    "webhooks_deliveries_list": "list_deliveries",
    "docs_search": "search",
    "feedback_submit": "submit",
}


def snake(value: str) -> str:
    value = re.sub(r"[-\s]+", "_", value)
    value = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", value)
    return value.lower()


def pascal(value: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[-_\s]+", value) if part)


def py_identifier(name: str) -> str:
    name = snake(name)
    return f"{name}_" if keyword.iskeyword(name) else name


def literal(value: Any) -> str:
    if value is None:
        return "None"
    if isinstance(value, bool):
        return "True" if value else "False"
    return json.dumps(value, ensure_ascii=False)


def docstring(text: Optional[str], indent: str) -> str:
    if not text:
        return ""
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').strip()
    lines = text.split("\n")
    if len(lines) == 1:
        return f'{indent}"""{lines[0]}"""\n'
    body = "\n".join(f"{indent}{line}" if line else "" for line in lines)
    return f'{indent}"""\n{body}\n{indent}"""\n'


def load_spec(source: Optional[str]) -> Dict[str, Any]:
    if source is None:
        return json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    if re.match(r"^https?://", source):
        with urllib.request.urlopen(source, timeout=60) as response:  # noqa: S310 (fixed https URL from the caller)
            text = response.read().decode("utf-8")
    else:
        text = Path(source).read_text(encoding="utf-8")
    spec = json.loads(text)
    # Same formatting as JSON.stringify(spec, null, 2) in the Node SDK and scripts/export-openapi.ts.
    SNAPSHOT.write_text(json.dumps(spec, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return spec


class Models:
    """Turns JSON Schemas into Python type expressions, collecting named TypedDicts on the way."""

    def __init__(self, spec: Dict[str, Any]) -> None:
        self.spec = spec
        self.schemas: Dict[str, Any] = spec["components"]["schemas"]
        self.blocks: List[str] = []
        self.names = set(self.schemas)
        self.closed = False

    def deref(self, schema: Optional[Dict[str, Any]]) -> Optional[Dict[str, Any]]:
        while schema and "$ref" in schema:
            schema = self.schemas[schema["$ref"][len(REF_PREFIX):]]
        return schema

    def ref_name(self, schema: Dict[str, Any]) -> Optional[str]:
        ref = schema.get("$ref")
        return ref[len(REF_PREFIX):] if ref else None

    def unique(self, name: str) -> str:
        candidate, n = name, 2
        while candidate in self.names:
            candidate, n = f"{name}{n}", n + 1
        self.names.add(candidate)
        return candidate

    def type_of(self, schema: Any, name_hint: str, quote: bool, prefix: str = "") -> str:
        """A type expression. `quote` wraps model names for places Python evaluates eagerly; `prefix`
        qualifies them (`models.Post`) outside models.py."""
        if schema is True or schema == {} or schema is None:
            return "Any"
        ref = self.ref_name(schema)
        if ref:
            return f'"{prefix}{ref}"' if quote else prefix + ref
        if "const" in schema:
            return f"Literal[{literal(schema['const'])}]"
        if "enum" in schema:
            values = [v for v in schema["enum"] if v is not None]
            expr = f"Literal[{', '.join(literal(v) for v in values)}]"
            return f"Optional[{expr}]" if None in schema["enum"] else expr
        if "anyOf" in schema or "oneOf" in schema:
            variants = schema.get("anyOf") or schema.get("oneOf")
            return self.union([self.type_of(v, name_hint, quote, prefix) for v in variants])
        kind = schema.get("type")
        if isinstance(kind, list):
            return self.union([self.type_of({**schema, "type": k}, name_hint, quote, prefix) for k in kind])
        if kind == "null":
            return "None"
        if kind == "string":
            return "str"
        if kind == "integer":
            return "int"
        if kind == "number":
            return "float"
        if kind == "boolean":
            return "bool"
        if kind == "array":
            return f"List[{self.type_of(schema.get('items'), name_hint + 'Item', quote, prefix)}]"
        if kind == "object" or "properties" in schema:
            if not schema.get("properties"):
                extra = schema.get("additionalProperties")
                value = "Any" if extra in (None, True, False) else self.type_of(extra, name_hint + "Value", quote, prefix)
                return f"Dict[str, {value}]"
            if self.closed:
                raise SystemExit(f"{name_hint}: an inline object outside components; add it to the extra models")
            name = self.unique(name_hint)
            self.typed_dict(name, schema)
            return f'"{prefix}{name}"' if quote else prefix + name
        return "Any"

    @staticmethod
    def union(types: List[str]) -> str:
        unique: List[str] = []
        for t in types:
            if t not in unique:
                unique.append(t)
        has_none = "None" in unique
        rest = [t for t in unique if t != "None"]
        if not rest:
            return "None"
        inner = rest[0] if len(rest) == 1 else f"Union[{', '.join(rest)}]"
        return f"Optional[{inner}]" if has_none else inner

    def typed_dict(self, name: str, schema: Dict[str, Any]) -> None:
        required = set(schema.get("required", []))
        fields: List[Tuple[str, str, Optional[str]]] = []
        for prop, prop_schema in schema["properties"].items():
            t = self.type_of(prop_schema, name + pascal(prop), quote=False)
            if prop not in required:
                t = f"NotRequired[{t}]"
            description = prop_schema.get("description") if isinstance(prop_schema, dict) else None
            fields.append((prop, t, description))
        functional = any(not p.isidentifier() or keyword.iskeyword(p) for p, _, _ in fields)
        lines: List[str] = []
        if functional:
            # Some keys are no Python identifiers (`from`, `single-image`): the call syntax takes them.
            lines.append(f"{name} = TypedDict(")
            lines.append(f'    "{name}",')
            lines.append("    {")
            for prop, t, _ in fields:
                lines.append(f'        "{prop}": {json.dumps(t, ensure_ascii=False)},')
            lines.append("    },")
            lines.append(")")
            if schema.get("description"):
                lines.append(f"{name}.__doc__ = {json.dumps(schema['description'], ensure_ascii=False)}")
        else:
            lines.append(f"class {name}(TypedDict):")
            doc = docstring(schema.get("description"), "    ")
            if doc:
                lines.append(doc.rstrip("\n"))
            if not fields:
                lines.append("    pass")
            for prop, t, description in fields:
                if description:
                    first = description.strip().split("\n")[0]
                    lines.append(f"    #: {first}")
                lines.append(f"    {prop}: {t}")
        self.blocks.append("\n".join(lines))

    def build(self, extra: Dict[str, Dict[str, Any]]) -> str:
        aliases: List[str] = []
        for name, schema in list(self.schemas.items()) + list(extra.items()):
            if schema.get("type") == "object" and schema.get("properties"):
                self.names.add(name)
                self.typed_dict(name, schema)
            else:
                doc = schema.get("description")
                comment = f"  # {doc.splitlines()[0]}" if doc and len(doc) < 100 else ""
                aliases.append(f"{name} = {self.type_of(schema, name, quote=True)}{comment}")
        head = [
            HEADER,
            "from __future__ import annotations",
            "",
            "from typing import Any, Dict, List, Optional, Union",
            "",
            "from typing_extensions import Literal, NotRequired, TypedDict",
            "",
        ]
        self.closed = True
        return "\n".join(head) + "\n" + "\n".join(aliases) + "\n\n\n" + "\n\n\n".join(self.blocks) + "\n"


def collect_operations(spec: Dict[str, Any], models: Models) -> Tuple[List[Dict[str, Any]], Dict[str, Dict[str, Any]]]:
    operations: List[Dict[str, Any]] = []
    extra_models: Dict[str, Dict[str, Any]] = {}
    for path, item in spec["paths"].items():
        for method in HTTP_METHODS:
            op = item.get(method)
            if not op:
                continue
            op_id = op["operationId"]
            tag = (op.get("tags") or ["default"])[0]
            prefix = tag.replace("-", "_") + "_"
            name = METHOD_NAMES.get(op_id) or snake(op_id[len(prefix):] if op_id.startswith(prefix) else op_id)
            params = op.get("parameters", [])
            path_params = sorted(
                [p["name"] for p in params if p["in"] == "path"], key=lambda n: path.index("{" + n + "}")
            )
            query = [p for p in params if p["in"] == "query"]
            body_schema = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            body_type = None
            if body_schema is not None:
                body_type = models.ref_name(body_schema)
                if body_type is None:
                    body_type = pascal(op_id) + "Body"
                    extra_models[body_type] = body_schema
            status = next(code for code in op["responses"] if re.match(r"^2\d\d$", code))
            response_schema = op["responses"][status].get("content", {}).get("application/json", {}).get("schema")
            response_type = "None"
            if response_schema is not None:
                response_type = models.ref_name(response_schema) or "Any"
            resolved = models.deref(response_schema) or {}
            props = resolved.get("properties", {})
            paginated = (
                method == "get"
                and any(p["name"] == "offset" for p in query)
                and props.get("data", {}).get("type") == "array"
                and "pagination" in props
            )
            item_type = models.ref_name(props["data"].get("items", {})) or "Any" if paginated else None
            operations.append(
                {
                    "id": op_id,
                    "tag": tag,
                    "name": name,
                    "method": method.upper(),
                    "path": path,
                    "summary": op.get("summary"),
                    "description": op.get("description"),
                    "path_params": path_params,
                    "query": query,
                    "body_type": body_type,
                    "body_required": bool(op.get("requestBody", {}).get("required")),
                    "response_type": response_type,
                    "idempotent": any(
                        p["in"] == "header" and p["name"].lower() == "idempotency-key" for p in params
                    ),
                    "paginated": paginated,
                    "item_type": item_type,
                }
            )
    return operations, extra_models


def method_source(op: Dict[str, Any], models: Models, is_async: bool) -> str:
    args = ["self"]
    for p in op["path_params"]:
        args.append(f"{py_identifier(p)}: str")
    if op["body_type"]:
        body = f"models.{op['body_type']}"
        args.append(f"body: {body}" if op["body_required"] else f"body: Optional[{body}] = None")
    keyword_args: List[str] = []
    query_map: List[Tuple[str, str]] = []
    for p in sorted(op["query"], key=lambda q: not q.get("required")):
        py_name = py_identifier(p["name"])
        t = models.type_of(p.get("schema", {}), "Query", quote=False, prefix="models.")
        keyword_args.append(f"{py_name}: {t}" if p.get("required") else f"{py_name}: Optional[{t}] = None")
        query_map.append((p["name"], py_name))
    if keyword_args:
        args.append("*")
        args.extend(keyword_args)
    options_type = "IdempotentRequestOptions" if op["idempotent"] else "RequestOptions"
    args.append(f"**options: Unpack[{options_type}]")

    path_expr = json.dumps(op["path"])
    if op["path_params"]:
        formatted = re.sub(r"\{(\w+)\}", lambda m: "{_path(" + py_identifier(m.group(1)) + ")}", op["path"])
        path_expr = f'f"{formatted}"'
    call_args = [json.dumps(op["method"]), path_expr]
    if query_map:
        call_args.append("query={" + ", ".join(f'"{api}": {py}' for api, py in query_map) + "}")
    if op["body_type"]:
        call_args.append("body=body")
    if op["idempotent"]:
        call_args.append("idempotent=True")
    call_args.append("options=options")

    if op["paginated"]:
        item = op["item_type"] if op["item_type"] == "Any" else f"models.{op['item_type']}"
        returns = f"{'AsyncPaginator' if is_async else 'SyncPage'}[{item}]"
        call = f"return self._client._paginate({', '.join(call_args)})"
        prefix = "def"
    else:
        returns = op["response_type"] if op["response_type"] in ("None", "Any") else f"models.{op['response_type']}"
        awaited = "await " if is_async else ""
        call = f"return {awaited}self._client._request({', '.join(call_args)})  # type: ignore[no-any-return]"
        prefix = "async def" if is_async else "def"

    notes = [op["summary"] or "", "", op["description"] or "", "", f"``{op['method']} {op['path']}``"]
    if op["idempotent"]:
        notes.append("Sends an ``Idempotency-Key``: yours (``idempotency_key=``), or a generated one kept across retries.")
    if op["paginated"]:
        notes.append(
            "Returns one page; iterate it "
            + ("with ``async for``" if is_async else "with ``for``")
            + " to walk every item across pages."
        )
    doc = docstring("\n".join(notes), "        ")
    signature = f"    {prefix} {op['name']}({', '.join(args)}) -> {returns}:\n"
    return signature + doc + f"        {call}\n"


def resources_source(operations: List[Dict[str, Any]], models: Models) -> str:
    tags: List[str] = []
    for op in operations:
        if op["tag"] not in tags:
            tags.append(op["tag"])
    out = [
        HEADER,
        "from __future__ import annotations",
        "",
        "from typing import TYPE_CHECKING, Any, Dict, List, Optional, Union",
        "",
        "from typing_extensions import Literal, Unpack",
        "",
        "from .._pagination import AsyncPaginator, SyncPage",
        "from .._types import IdempotentRequestOptions, RequestOptions, _path",
        "from . import models",
        "",
        "if TYPE_CHECKING:",
        "    from .._client import AsyncAmpost, Ampost",
        "",
    ]
    for is_async in (False, True):
        for tag in tags:
            cls = ("Async" if is_async else "") + pascal(tag)
            client_type = "AsyncAmpost" if is_async else "Ampost"
            out.append("")
            out.append(f"class {cls}:")
            out.append(f'    """``{tag}`` operations."""')
            out.append("")
            out.append(f"    def __init__(self, client: {client_type}) -> None:")
            out.append("        self._client = client")
            names = set()
            for op in (o for o in operations if o["tag"] == tag):
                if op["name"] in names:
                    raise SystemExit(f"{tag} has two methods named {op['name']}; add a METHOD_NAMES entry")
                names.add(op["name"])
                out.append("")
                out.append(method_source(op, models, is_async).rstrip("\n"))
            out.append("")
    for is_async in (False, True):
        base = "_AsyncResources" if is_async else "_SyncResources"
        out.append("")
        out.append(f"class {base}:")
        out.append(f'    """Every resource of the API, one attribute per tag. ``{"AsyncAmpost" if is_async else "Ampost"}`` sets them up."""')
        out.append("")
        for tag in tags:
            out.append(f"    {snake(tag)}: {('Async' if is_async else '') + pascal(tag)}")
        out.append("")
        out.append("    def _init_resources(self) -> None:")
        for tag in tags:
            cls = ("Async" if is_async else "") + pascal(tag)
            out.append(f"        self.{snake(tag)} = {cls}(self)  # type: ignore[arg-type]")
        out.append("")
    out.append("")
    out.append("#: Every operation, for tests and tooling.")
    out.append("OPERATIONS: List[Dict[str, Any]] = [")
    for op in operations:
        entry = {
            "operation_id": op["id"],
            "resource": snake(op["tag"]),
            "method": op["name"],
            "http_method": op["method"],
            "path": op["path"],
            "idempotent": op["idempotent"],
            "paginated": op["paginated"],
        }
        out.append(f"    {json.dumps(entry).replace('true', 'True').replace('false', 'False')},")
    out.append("]")
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--spec", help="URL or path of an OpenAPI document; saved as openapi.json first")
    args = parser.parse_args()
    spec = load_spec(args.spec)
    models = Models(spec)
    operations, extra_models = collect_operations(spec, models)
    models_py = models.build(extra_models)
    resources_py = resources_source(operations, models)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "__init__.py").write_text(HEADER, encoding="utf-8")
    (OUT / "models.py").write_text(models_py, encoding="utf-8")
    (OUT / "resources.py").write_text(resources_py, encoding="utf-8")
    print(f"Generated {len(operations)} operations from {spec['info']['title']} {spec['info']['version']}")


if __name__ == "__main__":
    main()
